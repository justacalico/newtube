import 'dart:convert';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:newtube/l10n/app_localizations.dart';
import 'package:newtube/models/video_info.dart';
import 'package:newtube/services/innertube_api.dart';
import 'package:newtube/state/app_state.dart';
import 'package:newtube/state/settings_store.dart';
import 'package:newtube/ui/pages/watch_page.dart';
import 'package:newtube/ui/widgets/player_view.dart';
import 'package:newtube/utils/captions.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'fakes.dart';

const _tracks = [
  CaptionTrack(url: 'https://cap/en', languageCode: 'en', name: 'English'),
  CaptionTrack(
    url: 'https://cap/de',
    languageCode: 'de',
    name: '',
    isAutoGenerated: true,
  ),
];

const _vtt = '''
WEBVTT
Kind: captions
Language: en

00:00:01.000 --> 00:00:03.500 align:start position:0%
Hello <c>world</c> &amp; friends

00:00:04.000 --> 00:00:06.000
second line
wraps here

bad --> line

00:00:09.000 --> 00:00:08.000
backwards

00:99:99.999 --> 00:99:99.999
bogus times

00:00:10.000 --> 00:00:12.000
''';

const _srv3 = '''<?xml version="1.0" encoding="utf-8" ?>
<timedtext format="3">
<body>
<p t="0" d="2000">first &amp; second</p>
<p t="2500">no duration</p>
<p d="500">no start</p>
<p t="6000" d="1000"></p>
</body>
</timedtext>''';

void main() {
  group('parseCaptions', () {
    test('parses vtt cues and strips markup', () {
      final cues = parseCaptions(_vtt);
      expect(cues, hasLength(2));
      expect(cues[0].start, const Duration(seconds: 1));
      expect(cues[0].end, const Duration(milliseconds: 3500));
      expect(cues[0].text, 'Hello world & friends');
      expect(cues[1].text, 'second line\nwraps here');
    });

    test('parses srv3 xml cues', () {
      final cues = parseCaptions(_srv3);
      expect(cues, hasLength(2));
      expect(cues[0].text, 'first & second');
      expect(cues[0].end, const Duration(milliseconds: 2000));
      expect(cues[1].end, const Duration(milliseconds: 4500));
    });

    test('invalid xml returns empty', () {
      expect(parseCaptions('<broken'), isEmpty);
      expect(parseCaptions(''), isEmpty);
      expect(parseCaptions('plain text only'), isEmpty);
    });
  });

  group('captionCueAt', () {
    const cues = [
      CaptionCue(
        start: Duration(seconds: 1),
        end: Duration(seconds: 3),
        text: 'a',
      ),
      CaptionCue(
        start: Duration(seconds: 5),
        end: Duration(seconds: 7),
        text: 'b',
      ),
    ];

    test('returns the cue covering the position', () {
      expect(captionCueAt(cues, const Duration(seconds: 2))?.text, 'a');
      expect(captionCueAt(cues, const Duration(seconds: 6))?.text, 'b');
    });

    test('returns null outside cue ranges', () {
      expect(captionCueAt(cues, Duration.zero), isNull);
      expect(captionCueAt(cues, const Duration(seconds: 4)), isNull);
      expect(captionCueAt(cues, const Duration(minutes: 1)), isNull);
      expect(captionCueAt(const [], Duration.zero), isNull);
    });
  });

  group('innertube captions', () {
    test('videoDetails parses caption tracks', () async {
      final api = InnertubeApi(
        httpClient: MockClient((request) async {
          if (request.method != 'POST') {
            return http.Response.bytes(const [], 206);
          }
          return http.Response.bytes(
            utf8.encode(
              jsonEncode({
                'videoDetails': {'title': 'Vid'},
                'captions': {
                  'playerCaptionsTracklistRenderer': {
                    'captionTracks': [
                      {
                        'baseUrl': 'https://cap/en',
                        'languageCode': 'en',
                        'name': {
                          'runs': [
                            {'text': 'English'},
                          ],
                        },
                      },
                      {
                        'baseUrl': 'https://cap/en-asr',
                        'languageCode': 'en',
                        'kind': 'asr',
                      },
                      {'noUrl': true},
                      'junk',
                    ],
                  },
                },
              }),
            ),
            200,
          );
        }),
      );
      final d = await api.videoDetails('v');
      expect(d.captions, hasLength(2));
      expect(d.captions[0].name, 'English');
      expect(d.captions[1].name, 'en');
      expect(d.captions[1].isAutoGenerated, isTrue);
    });

    test('captions fetches vtt cues', () async {
      String? requested;
      final api = InnertubeApi(
        httpClient: MockClient((request) async {
          requested = request.url.toString();
          return http.Response(_vtt, 200);
        }),
      );
      final cues = await api.captions(_tracks.first);
      expect(requested, 'https://cap/en&fmt=vtt');
      expect(cues.first.text, 'Hello world & friends');
    });

    test('captions keeps an existing fmt param', () async {
      String? requested;
      final api = InnertubeApi(
        httpClient: MockClient((request) async {
          requested = request.url.toString();
          return http.Response(_vtt, 200);
        }),
      );
      await api.captions(
        const CaptionTrack(
          url: 'https://cap/en?fmt=srv3',
          languageCode: 'en',
          name: 'English',
        ),
      );
      expect(requested, 'https://cap/en?fmt=srv3');
    });

    test('captions throws on http errors', () async {
      final api = InnertubeApi(
        httpClient: MockClient((_) async => http.Response('x', 500)),
      );
      expect(
        () => api.captions(_tracks.first),
        throwsA(isA<InnertubeException>()),
      );
    });
  });

  group('player captions', () {
    Future<void> pumpPlayer(
      WidgetTester tester,
      FakePlayerController player,
      FakeYouTubeApi api, {
      CaptionTrack? selected,
      ValueChanged<CaptionTrack?>? onSelected,
    }) async {
      final state = await testState(api: api);
      await tester.pumpWidget(
        AppScope(
          state: state,
          child: MaterialApp(
            supportedLocales: AppLocalizations.supportedLocales,
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            home: Scaffold(
              body: PlayerView(
                player: player,
                streams: testStreams,
                current: testStreams[1],
                onQualitySelected: (_) {},
                onAudioSelected: (_) {},
                onToggleFullscreen: () {},
                captions: _tracks,
                selectedCaption: selected,
                onCaptionSelected: onSelected,
              ),
            ),
          ),
        ),
      );
    }

    testWidgets('captions menu lists tracks and off', (tester) async {
      final player = FakePlayerController();
      final api = FakeYouTubeApi();
      CaptionTrack? selected = _tracks.first;
      await pumpPlayer(
        tester,
        player,
        api,
        selected: selected,
        onSelected: (t) => selected = t,
      );
      await tester.pumpAndSettle();
      expect(api.captionRequests.single, _tracks.first);

      await tester.tap(find.byTooltip('Settings'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Captions'));
      await tester.pumpAndSettle();
      expect(find.text('English'), findsOneWidget);
      expect(find.text('de'), findsOneWidget);
      expect(find.text('Off'), findsOneWidget);
      expect(find.byIcon(Icons.check), findsOneWidget);

      await tester.tap(find.text('de'));
      await tester.pumpAndSettle();
      expect(selected, _tracks[1]);
    });

    testWidgets('cue overlay follows the position', (tester) async {
      final player = FakePlayerController();
      final api = FakeYouTubeApi()
        ..captionCues = const [
          CaptionCue(
            start: Duration(seconds: 1),
            end: Duration(seconds: 3),
            text: 'hello there',
          ),
        ];
      await pumpPlayer(tester, player, api, selected: _tracks.first);
      await tester.pumpAndSettle();
      expect(find.text('hello there'), findsNothing);

      player.emitPosition(const Duration(seconds: 2));
      await tester.pump();
      await tester.pump();
      expect(find.text('hello there'), findsOneWidget);

      player.emitPosition(const Duration(seconds: 4));
      await tester.pump();
      await tester.pump();
      expect(find.text('hello there'), findsNothing);
    });

    testWidgets('switching and clearing tracks reloads cues', (tester) async {
      final player = FakePlayerController();
      final api = FakeYouTubeApi()
        ..captionCues = const [
          CaptionCue(
            start: Duration.zero,
            end: Duration(minutes: 1),
            text: 'showing',
          ),
        ];
      final state = await testState(api: api);
      var selected = _tracks.first;
      late StateSetter rebuild;
      await tester.pumpWidget(
        AppScope(
          state: state,
          child: MaterialApp(
            supportedLocales: AppLocalizations.supportedLocales,
            localizationsDelegates: AppLocalizations.localizationsDelegates,
            home: Scaffold(
              body: StatefulBuilder(
                builder: (context, setState) {
                  rebuild = setState;
                  return PlayerView(
                    player: player,
                    streams: testStreams,
                    current: testStreams[1],
                    onQualitySelected: (_) {},
                    onAudioSelected: (_) {},
                    onToggleFullscreen: () {},
                    captions: _tracks,
                    selectedCaption: selected,
                    onCaptionSelected: (t) => setState(() => selected = t!),
                  );
                },
              ),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();
      expect(find.text('showing'), findsOneWidget);

      rebuild(() => selected = _tracks[1]);
      await tester.pump();
      await tester.pumpAndSettle();
      expect(api.captionRequests, [_tracks.first, _tracks[1]]);
      expect(find.text('showing'), findsOneWidget);

      api.captionsError = StateError('boom');
      rebuild(() => selected = _tracks.first);
      await tester.pumpAndSettle();
      expect(find.text('showing'), findsOneWidget);
    });

    testWidgets('captions menu hidden without callback', (tester) async {
      final player = FakePlayerController();
      final api = FakeYouTubeApi();
      await pumpPlayer(tester, player, api);
      await tester.pumpAndSettle();

      await tester.tap(find.byTooltip('Settings'));
      await tester.pumpAndSettle();
      expect(find.text('Captions'), findsNothing);
    });
  });

  group('watch page captions', () {
    FakeYouTubeApi captionApi() => FakeYouTubeApi(
      details: const VideoDetails(
        info: VideoInfo(
          id: 'v1',
          title: 'First video',
          author: 'Channel One',
          channelId: 'c1',
        ),
        description: 'A video description',
        streams: testStreams,
        captions: _tracks,
      ),
    );

    testWidgets('auto-selects the saved caption language', (tester) async {
      final api = captionApi();
      final state = await testState(
        api: api,
        player: FakePlayerController(),
        settings: SettingsStore(captionsEnabled: true, captionLanguage: 'de'),
      );
      await pumpPage(tester, state, WatchPage(video: testVideos.first));
      await tester.pumpAndSettle();
      expect(api.captionRequests.single, _tracks[1]);
    });

    testWidgets('falls back to the first track', (tester) async {
      final api = captionApi();
      final state = await testState(
        api: api,
        player: FakePlayerController(),
        settings: SettingsStore(captionsEnabled: true, captionLanguage: 'fr'),
      );
      await pumpPage(tester, state, WatchPage(video: testVideos.first));
      await tester.pumpAndSettle();
      expect(api.captionRequests.single, _tracks.first);
    });

    testWidgets('captions switch inside fullscreen', (tester) async {
      final api = captionApi();
      final player = FakePlayerController();
      final state = await testState(api: api, player: player);
      await pumpPage(tester, state, WatchPage(video: testVideos.first));
      await tester.pumpAndSettle();

      await tester.tap(find.byTooltip('Fullscreen'));
      await tester.pumpAndSettle();
      await tester.tap(find.byTooltip('Settings'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Captions'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('English'));
      await tester.pumpAndSettle();

      expect(state.settings.captionsEnabled, isTrue);
      expect(state.settings.captionLanguage, 'en');
      expect(api.captionRequests.single.languageCode, 'en');
    });

    testWidgets('stays off when captions are disabled', (tester) async {
      final api = captionApi();
      final state = await testState(api: api, player: FakePlayerController());
      await pumpPage(tester, state, WatchPage(video: testVideos.first));
      await tester.pumpAndSettle();
      expect(api.captionRequests, isEmpty);
    });

    testWidgets('selecting a caption track persists the setting', (
      tester,
    ) async {
      final api = captionApi();
      final state = await testState(api: api, player: FakePlayerController());
      await pumpPage(tester, state, WatchPage(video: testVideos.first));
      await tester.pumpAndSettle();

      await tester.tap(find.byTooltip('Settings'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Captions'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('English'));
      await tester.pumpAndSettle();

      expect(state.settings.captionsEnabled, isTrue);
      expect(state.settings.captionLanguage, 'en');
      expect(api.captionRequests.single.languageCode, 'en');

      await tester.tap(find.byTooltip('Settings'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Captions'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Off'));
      await tester.pumpAndSettle();

      expect(state.settings.captionsEnabled, isFalse);
      expect(state.settings.captionLanguage, '');
    });
  });

  group('caption settings', () {
    test(
      'captionsEnabled and captionLanguage round-trip through prefs',
      () async {
        SharedPreferences.setMockInitialValues({});
        final prefs = await SharedPreferences.getInstance();
        final settings = await SettingsStore.load(prefs);
        expect(settings.captionsEnabled, isFalse);
        expect(settings.captionLanguage, '');

        await settings.setCaptionsEnabled(true, prefs);
        await settings.setCaptionLanguage('ga', prefs);
        expect(prefs.getBool('captions_enabled'), isTrue);
        expect(prefs.getString('caption_language'), 'ga');

        await settings.setCaptionLanguage(null, prefs);
        expect(settings.captionLanguage, '');

        final reloaded = await SettingsStore.load(prefs);
        expect(reloaded.captionsEnabled, isTrue);
      },
    );
  });
}
