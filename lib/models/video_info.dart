class PlaylistInfo {
  final String id;
  final String title;
  final String author;
  final String? thumbnailUrl;
  final int videoCount;
  final List<VideoInfo> videos;
  final String? continuation;

  const PlaylistInfo({
    required this.id,
    required this.title,
    this.author = '',
    this.thumbnailUrl,
    this.videoCount = 0,
    this.videos = const [],
    this.continuation,
  });

  PlaylistInfo withContinuation(List<VideoInfo> more, String? next) =>
      PlaylistInfo(
        id: id,
        title: title,
        author: author,
        thumbnailUrl: thumbnailUrl,
        videoCount: videoCount,
        videos: [...videos, ...more],
        continuation: next,
      );
}

